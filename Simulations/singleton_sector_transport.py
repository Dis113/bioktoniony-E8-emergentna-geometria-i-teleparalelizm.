"""POM-5: an OPTIONAL internal SU(2) transport prototype between H_i sectors.

Derived inputs: local quaternion-subalgebra frames generated by the 16-real
bi-octonion fields of POM-3. The Procrustes rule itself is a NEW POSTULATE
of POM-5, not derived from the graph Hamiltonian. This is NOT an AdS4
Sp(4,R) connection, a Lorentz spin connection, or physical teleparallelism.
"""
import numpy as np
from scipy.spatial.transform import Rotation
from sector_vacuum_probe import quaternion_sector

sigma=np.array([
    [[0,1],[1,0]],
    [[0,-1j],[1j,0]],
    [[1,0],[0,-1]]
],dtype=complex)


def oriented_so3_overlap(Bi,Bj):
    """Map local imaginary frame i to j by closest SO(3) polar factor."""
    overlap=Bj[:,1:].T@Bi[:,1:]
    U,s,Vh=np.linalg.svd(overlap)
    D=np.diag([1.,1.,np.linalg.det(U@Vh)])
    R=U@D@Vh
    assert np.allclose(R.T@R,np.eye(3),atol=1e-10)
    assert np.isclose(np.linalg.det(R),1.,atol=1e-10)
    return R,s


def spin_lift(R):
    """One chosen local lift SO(3)->SU(2); sign is intrinsically ambiguous."""
    x,y,z,w=Rotation.from_matrix(R).as_quat()
    S=w*np.eye(2,dtype=complex)-1j*(x*sigma[0]+y*sigma[1]+z*sigma[2])
    assert np.allclose(S.conj().T@S,np.eye(2),atol=1e-10)
    assert np.isclose(np.linalg.det(S),1.,atol=1e-10)
    for k in range(3):
        rotated=S@sigma[k]@S.conj().T
        expected=sum(R[j,k]*sigma[j] for j in range(3))
        assert np.allclose(rotated,expected,atol=1e-10)
    return S


def main():
    rng=np.random.default_rng(5130)
    psi=[]
    for _ in range(3):
        p=np.zeros(16)
        p[1:8]=rng.normal(size=7)
        p[9:16]=rng.normal(size=7)
        psi.append(p)
    B=[quaternion_sector(p) for p in psi]
    R01,s01=oriented_so3_overlap(B[0],B[1])
    R12,s12=oriented_so3_overlap(B[1],B[2])
    R20,s20=oriented_so3_overlap(B[2],B[0])
    R10,_=oriented_so3_overlap(B[1],B[0])
    assert np.allclose(R10,R01.T,atol=1e-10)
    W=R20@R12@R01
    dev=float(np.linalg.norm(W-np.eye(3)))
    assert dev>1e-5
    S01=spin_lift(R01)
    S12=spin_lift(R12)
    S20=spin_lift(R20)
    SW=S20@S12@S01
    assert np.allclose(SW.conj().T@SW,np.eye(2))
    # This is an internal SU(2) transport. Its spinor lift does not
    # provide the boosts of SL(2,C), nor the AdS4 group Sp(4,R).
    for s in (s01,s12,s20):
        assert np.min(s)>=0 and np.max(s)<=1+1e-10
    print("POM-5: internal SO(3) Procrustes and SU(2) lift PASS")
    print("POM-5: nontrivial three-sector loop norm:",dev)
    print("POM-5: overlap singular values:",s01,s12,s20)
    print("LIMIT: transport is postulated and compact SU(2) only; no AdS4 group or TEGR.")


if __name__=="__main__":
    main()
