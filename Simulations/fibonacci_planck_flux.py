"""POM-9: Planck-scale PHASE, Fibonacci rational flux and sector overlaps.

This is a CONDITIONAL 2D Peierls/Hofstadter model with a *given* 2D graph
and an *external* magnetic flux alpha=Phi/(h/e). The Fibonacci rational
approximants describe a DIMENSIONLESS ratio, not Planck's constant h.

What is POM-specific:
- quaternionic sectors A/B come from bi-octonion states of POM-3;
- scalar x-link hopping is derived by the postulated overlap rule
  t_m=1+(1/5)*(Tr(P_m P_(m+1))/4 -1);
- the Fibonacci sector word and the flux p/q are prescribed, NOT
  spontaneously generated by the POM Hamiltonian;
- the known TKNN/Harper Chern and continued-fraction theorems are NOT
  re-proved here; the finite numerical check tests this coupling.

No 3+1 spacetime, Planck-length lattice, Standard Model field,
fermionic quantization, Maxwell or teleparallel GR is derived.
"""
from __future__ import annotations

import math
import numpy as np

from spectral_topological_probe import concrete_sectors

ALPHA_GOLD = (math.sqrt(5)-1)/2
GAP_GRID = 25
EPSILON_PERTURB = .08


def approximants():
    """Fibonacci continued-fraction convergents (pre-existing number theory)."""
    fib = [0, 1]
    while fib[-1] < 55:
        fib.append(fib[-1] + fib[-2])
    pairs = [(fib[k-1], fib[k]) for k in range(5, len(fib))
             if 5 <= fib[k] <= 34]
    assert pairs == [(3,5),(5,8),(8,13),(13,21),(21,34)]
    for p,q in pairs:
        assert math.gcd(p,q)==1
        assert abs(p/q-ALPHA_GOLD) < 1/q**2
    return pairs


def mechanical_word(p,q):
    """A rational Fibonacci/Sturmian-word approximant with q sites."""
    return np.array([((n+1)*p)//q-(n*p)//q for n in range(q)],
                    dtype=np.int64)


def sector_bonds(p,q,kappa=.2):
    """Construct *specific* POM-3 projectors, then compare neighboring sectors."""
    (_, _),(PA,PB),qAB,_=concrete_sectors()
    assert np.isclose(qAB,5/8,atol=1e-12)
    word=mechanical_word(p,q)
    projectors=np.array([PB if int(a) else PA for a in word])
    local_overlap=np.array([np.trace(projectors[n]@
                               projectors[(n+1)%q])/4
                            for n in range(q)],dtype=float)
    assert np.allclose(local_overlap,
                       np.where(word==np.roll(word,-1),1,5/8))
    hopping=1 + kappa*(local_overlap-1)
    if kappa>0:
        assert np.allclose(np.unique(np.round(hopping,12)),[37/40,1.])
        assert sum(abs(hopping-37/40)<1e-10)==2*min(p,q-p)
    else:
        assert np.allclose(hopping,1.)
    return word,local_overlap,hopping


def magnetic_bloch(p,q,phi,ky,hop,onsite=0.):
    """q×q magnetic-cell Bloch Hamiltonian, with boundary twist phi=q*kx.

    Uniform external flux alpha=p/q is encoded by the y-dispersion.
    """
    m=np.arange(q)
    H=np.zeros((q,q),dtype=complex)
    H[np.diag_indices(q)] = (-2*np.cos(ky+2*np.pi*p*m/q)
                              +onsite*np.sin(2*np.pi*m/q))
    for j in range(q-1):
        H[j,j+1]=H[j+1,j]=-hop[j]
    H[0,q-1]=-hop[-1]*np.exp(-1j*phi)
    H[q-1,0]=-hop[-1]*np.exp(1j*phi)
    assert np.allclose(H,H.conj().T,atol=1e-12)
    return H


def spectral_certification(p,q,grid=GAP_GRID,onsite=0.,kappa=.2):
    """Fukui-Hatsugai-Suzuki lattice Chern estimate + conservative mesh bound.

    The mesh bound follows standard eigenvalue perturbation estimates:
      ||H(phi,ky)-H(phi0,ky0)|| <= max_hop*|dphi|+2|dky|,
    nearest mesh distances at most pi/grid in each coordinate. Hence
      gap_all_BZ >= sampled_min_gap-2*(max_hop+2)*pi/grid.
    This is an ANALYTIC inequality conditional on the numerical
    eigensolver's sample values; not a certified interval-arithmetic proof.
    """
    word,overlap,hop=sector_bonds(p,q,kappa=kappa)
    eigenframes=[]
    min_sample_gap=float("inf")
    for i in range(grid):
        row=[]
        for j in range(grid):
            eig,V=np.linalg.eigh(magnetic_bloch(
                p,q,2*np.pi*i/grid,2*np.pi*j/grid,hop,onsite))
            min_sample_gap=min(min_sample_gap,float(eig[p]-eig[p-1]))
            row.append(V[:,:p])
        eigenframes.append(row)
    links=np.empty((grid,grid,2),dtype=complex)
    for i in range(grid):
        for j in range(grid):
            for direction,(i2,j2) in enumerate(
                    [((i+1)%grid,j),(i,(j+1)%grid)]):
                matrix=eigenframes[i][j].conj().T@eigenframes[i2][j2]
                det=np.linalg.det(matrix)
                assert abs(det)>1e-8,"Chern mesh too coarse"
                links[i,j,direction]=det/abs(det)
    total=0.
    for i in range(grid):
        for j in range(grid):
            phase=links[i,j,0]*links[(i+1)%grid,j,1] / (
                  links[i,(j+1)%grid,0]*links[i,j,1])
            total+=np.angle(phase)
    chern=round(total/(2*np.pi))
    assert abs(total/(2*np.pi)-chern)<1e-8
    conservative=min_sample_gap-2*(np.max(hop)+2)*np.pi/grid
    return dict(p=p,q=q,chern=chern,mesh_gap=min_sample_gap,
                conservative_BZ_gap=conservative,
                min_t=float(np.min(hop)),max_t=float(np.max(hop)),
                weak_links=int(sum(hop<.99)),
                error_alpha=abs(p/q-ALPHA_GOLD))


def test_stability():
    stats=[]
    for p,q in approximants():
        base=spectral_certification(p,q)
        perturbed=spectral_certification(p,q,onsite=EPSILON_PERTURB)
        assert base["chern"]==perturbed["chern"]==-1
        assert base["conservative_BZ_gap"]>0.72
        assert perturbed["conservative_BZ_gap"]>0.70
        # More importantly, EVERY intermediate onsite perturbation
        # |delta|<=0.08 keeps an open gap by the known Weyl inequality
        # gap(delta) >= gap(0) - 2*|delta|.
        assert base["conservative_BZ_gap"]-2*EPSILON_PERTURB>.55
        assert base["weak_links"]==2*(q-p)
        stats.append((base,perturbed))
    # Independent irrational control: the silver mean [0;2,2,2,...]
    # is also badly approximable, and yields robust Chern gaps. Golden
    # ratio is NOT uniquely selected by this phenomenological model.
    silver=[]
    silver_alpha=math.sqrt(2)-1
    for p,q in [(2,5),(5,12),(12,29)]:
        assert abs(p/q-silver_alpha)<1/q**2
        check=spectral_certification(p,q)
        assert check["chern"]==-1
        assert check["conservative_BZ_gap"]>.69
        assert check["weak_links"]==2*p
        silver.append(check)
    # Crucial negative control: with *no bi-octonion overlap modulation*
    # the external Hofstadter magnetic field still produces the SAME Chern
    # number. Thus this topological index is NOT an emergent POM invariant.
    control=spectral_certification(8,13,kappa=0.)
    assert control["chern"]==-1 and control["conservative_BZ_gap"]>.7
    return stats,control,silver


